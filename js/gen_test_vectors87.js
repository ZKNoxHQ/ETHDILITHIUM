// Description: writes the ML-DSA-87 test vectors of the Solidity test suite
// from the NIST files in test/KAT/ (run from the repository root:
// `node js/gen_test_vectors87.js [rspCounts]`, default 10):
//   - test/dilithium87KATS.t.sol: count 0 of PQCsignKAT_Dilithium5.rsp as a
//     literal test (on-chain key, signature and message as hex literals, no
//     JSON parsing involved);
//   - test/KAT/mldsa87_vectors.json: the NIST ACVP ML-DSA-87 sigVer vectors
//     (external interface, pure, contexts of 0..255 bytes, valid and
//     corrupted signatures), the first `rspCounts` vectors of the .rsp and
//     signer vectors, each with the on-chain public key blob, read by
//     test/dilithium87_vectors.t.sol and test/dilithium87_key.t.sol;
//   - test/KAT/mldsa87_kat0.json: count 0 alone with its expanded key, for the
//     kernel tests.
import fs from 'fs';
import { expandPublicKey87, encodePublicKey87, hexToBytes, bytesToHex, keygen, sign, verify, PARAMS } from './mldsa87.js';
import { keccak_256 } from '@noble/hashes/sha3.js';
import { parseRsp } from './kat_rsp.js';

const KAT = 'test/KAT';
const rspCounts = process.argv[2] ? parseInt(process.argv[2], 10) : 10;

const rsp = parseRsp(fs.readFileSync(`${KAT}/PQCsignKAT_Dilithium5.rsp`, 'utf8'));

// ---------------------------------------------------------------- literal test
function literalTest(v) {
  const blob = encodePublicKey87(expandPublicKey87(v.pk));
  const sig = v.sm.slice(0, PARAMS.SIG_BYTES);
  const hex = (b) => Buffer.from(b).toString('hex');
  let s = '';
  s += '// SPDX-License-Identifier: UNLICENSED\n';
  s += 'pragma solidity ^0.8.13;\n';
  s += '// GENERATED by js/gen_test_vectors87.js -- do not edit by hand.\n';
  s += '// NIST reference implementation KAT (pq-crystals/dilithium, FIPS 204 ML-DSA-87),\n';
  s += `// test/KAT/PQCsignKAT_Dilithium5.rsp, count = ${v.count}: pk expanded to the on-chain\n`;
  s += '// form (A_hat = ExpandA(rho), t1 = NTT(t1 * 2^13), tr = SHAKE256(pk, 64)) by js/mldsa87.js.\n\n';
  s += 'import {Test, console} from "forge-std/Test.sol";\n';
  s += 'import {ZKNOX_dilithium87} from "../src/ZKNOX_dilithium87.sol";\n';
  s += 'import {F1600Helper} from "./F1600Helper.sol";\n\n';
  s += 'contract KATDilithium87Test is Test {\n';
  s += '    ZKNOX_dilithium87 dilithium;\n\n';
  s += '    function setUp() public {\n';
  s += '        dilithium = new ZKNOX_dilithium87(F1600Helper.deploy(vm));\n';
  s += '    }\n\n';
  s += '    // pubkey (FIPS 204, 2592 bytes) =\n';
  s += `    // ${hex(v.pk)}\n`;
  s += '    // expanded as the verifier takes it: the 64 polynomials in reading order\n';
  s += '    // (flat index f < 56 is A[f / 7][f % 7], f >= 56 is t1[f - 56]), then tr\n';
  s += '    function _pubKey() internal pure returns (bytes memory) {\n';
  s += `        return hex"${blob.slice(2)}";\n`;
  s += '    }\n\n';
  s += '    function _signature() internal pure returns (bytes memory) {\n';
  s += `        // sm = signature (${PARAMS.SIG_BYTES} bytes) || message\n`;
  s += `        return hex"${hex(sig)}";\n`;
  s += '    }\n\n';
  s += '    function _message() internal pure returns (bytes memory) {\n';
  s += `        // mlen = ${v.mlen}\n`;
  s += `        return hex"${hex(v.msg)}";\n`;
  s += '    }\n\n';
  s += '    function testVerify() public view {\n';
  s += '        bytes memory pk = _pubKey();\n';
  s += '        bytes memory sig = _signature();\n';
  s += '        bytes memory msgs = _message();\n\n';
  s += '        uint256 gasStart = gasleft();\n';
  s += '        bool ver = dilithium.verify(pk, msgs, sig, "");\n';
  s += '        uint256 gasUsed = gasStart - gasleft();\n';
  s += '        console.log("Gas used:", gasUsed);\n';
  s += '        assertTrue(ver);\n';
  s += '    }\n\n';
  s += '    /// one corrupted byte in each of the three fields of the signature, and a\n';
  s += '    /// corrupted message: all rejected\n';
  s += '    function testRejects() public view {\n';
  s += '        bytes memory pk = _pubKey();\n';
  s += '        bytes memory msgs = _message();\n';
  s += '        uint256[3] memory positions = [uint256(5), 1000, 4600]; // c~, z, h\n';
  s += '        for (uint256 i = 0; i < 3; i++) {\n';
  s += '            bytes memory sig = _signature();\n';
  s += '            sig[positions[i]] ^= 0x01;\n';
  s += '            assertFalse(dilithium.verify(pk, msgs, sig, ""));\n';
  s += '        }\n';
  s += '        bytes memory badMsg = _message();\n';
  s += '        badMsg[0] ^= 0x01;\n';
  s += '        assertFalse(dilithium.verify(pk, badMsg, _signature(), ""));\n';
  s += "        // a context changes M': the signature was made with an empty context\n";
  s += '        assertFalse(dilithium.verify(pk, msgs, _signature(), hex"00"));\n';
  s += '    }\n';
  s += '}\n';
  return s;
}

fs.writeFileSync('test/dilithium87KATS.t.sol', literalTest(rsp[0]));
console.log('wrote test/dilithium87KATS.t.sol (rsp count 0)');

// ---------------------------------------------------------------- JSON vectors
const vectors = [];
const sigVer = JSON.parse(fs.readFileSync(`${KAT}/ACVP_ML-DSA-87_sigVer-FIPS204.json`, 'utf8'));
for (const g of sigVer.testGroups) {
  if (g.signatureInterface !== 'external' || g.preHash !== 'pure') continue;
  for (const t of g.tests) {
    const pk = hexToBytes(t.pk);
    vectors.push({
      name: `ACVP ML-DSA-87 sigVer tgId ${g.tgId} tcId ${t.tcId}: ${t.reason}`,
      source: 'usnistgov/ACVP-Server gen-val/json-files/ML-DSA-sigVer-FIPS204/internalProjection.json',
      tcId: t.tcId,
      pk: bytesToHex(pk),
      blob: encodePublicKey87(expandPublicKey87(pk)),
      msg: '0x' + t.message.toLowerCase(),
      ctx: '0x' + t.context.toLowerCase(),
      sig: '0x' + t.signature.toLowerCase(),
      valid: t.testPassed,
    });
  }
}
console.log(`ACVP sigVer (external, pure): ${vectors.length} vectors`);
for (const v of rsp.slice(0, rspCounts)) {
  vectors.push({
    name: `PQCsignKAT_Dilithium5.rsp count ${v.count}`,
    source: 'pq-crystals/dilithium ref/nistkat/PQCgenKAT_sign (FIPS 204 ML-DSA-87)',
    tcId: v.count,
    pk: bytesToHex(v.pk),
    blob: encodePublicKey87(expandPublicKey87(v.pk)),
    msg: bytesToHex(v.msg),
    ctx: '0x',
    sig: bytesToHex(v.sm.slice(0, PARAMS.SIG_BYTES)),
    valid: true,
  });
}
// the JS signer itself: a key from a fixed seed, a message with a context,
// deterministic and hedged signatures (the hedged one with a fixed rnd)
{
  const { publicKey, secretKey } = keygen(hexToBytes('0x' + 'deadbeef'.repeat(8)));
  const msg = new TextEncoder().encode('ETHDILITHIUM ML-DSA-87 js signer test message');
  const ctx = hexToBytes('0x5a4b4e4f58'); // "ZKNOX"
  const blob = encodePublicKey87(expandPublicKey87(publicKey));
  const det = sign(msg, secretKey, { context: ctx });
  const hedged = sign(msg, secretKey, { context: ctx, rnd: hexToBytes('0x' + '01'.repeat(32)) });
  if (!verify(det, msg, publicKey, ctx) || !verify(hedged, msg, publicKey, ctx)) throw new Error('js signer self-check failed');
  for (const [label, sig] of [['deterministic', det], ['hedged (rnd = 0x01..01)', hedged]]) {
    vectors.push({
      name: `js/mldsa87.js keygen(seed 0xdeadbeef..) + sign(msg, ctx "ZKNOX"), ${label}`,
      source: 'js/mldsa87.js (@noble/post-quantum ml_dsa87)',
      tcId: 1000 + vectors.length,
      pk: bytesToHex(publicKey),
      blob,
      msg: bytesToHex(msg),
      ctx: bytesToHex(ctx),
      sig: bytesToHex(sig),
      valid: true,
    });
  }
  // the same signature with another context: rejected
  vectors.push({
    name: 'js/mldsa87.js deterministic signature with the wrong context',
    source: 'js/mldsa87.js (@noble/post-quantum ml_dsa87)',
    tcId: 1000 + vectors.length,
    pk: bytesToHex(publicKey),
    blob,
    msg: bytesToHex(msg),
    ctx: '0x5a4b4e4f',
    sig: bytesToHex(det),
    valid: false,
  });
}
// the ISigVerifier interface verify(pk, bytes32 hash, sig) checks the pure
// ML-DSA-87 signature of the 32-byte hash with an empty context: one made here
// with the secret key of .rsp count 0
const hash = keccak_256(new TextEncoder().encode('ZKNOX ML-DSA-87 hash32 test vector'));
const hashSig = sign(hash, rsp[0].sk, { deterministic: true });
if (!verify(hashSig, hash, rsp[0].pk)) throw new Error('hash32 signature does not verify');
const hash32 = { key: 'PQCsignKAT_Dilithium5.rsp count 0', hash: bytesToHex(hash), sig: bytesToHex(hashSig) };
fs.writeFileSync(`${KAT}/mldsa87_vectors.json`, JSON.stringify({ count: vectors.length, hash32, vectors }, null, 1));
// count 0 alone, with its expanded key, for the kernel tests (small file, fast to parse)
{
  const v = rsp[0];
  const { aHat, t1Hat, tr } = expandPublicKey87(v.pk);
  const kat0 = {
    source: 'PQCsignKAT_Dilithium5.rsp count 0',
    pk: bytesToHex(v.pk),
    blob: encodePublicKey87({ aHat, t1Hat, tr }),
    tr: bytesToHex(tr),
    msg: bytesToHex(v.msg),
    sig: bytesToHex(v.sm.slice(0, PARAMS.SIG_BYTES)),
  };
  fs.writeFileSync(`${KAT}/mldsa87_kat0.json`, JSON.stringify(kat0, null, 1));
  console.log(`wrote ${KAT}/mldsa87_kat0.json`);
}
console.log(`wrote ${KAT}/mldsa87_vectors.json: ${vectors.length} vectors (${rspCounts} from the .rsp)`);
